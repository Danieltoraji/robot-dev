"""实测动作常数（单一真源，motion_calib.py）

来源：2026-09-25 机器人动作标定。做法是"每组 N 次 × 多组"，报出单次均值、
±3σ 与**组间极差**。三个数都要看：±3σ 是组内散布，组间极差才是换一组
（换电量、换地面）之后单次值的漂移量。

用法约定（重要）
----------------
- **关卡（levels 下）**：把这些值当**预测值**，用来估算步数、设定死区与容差。
- **仿真器（sim 下）**：把这些值当**真值**，在其上叠加噪声，模拟真实动作散布。

两边数值相同，但扮演的角色不同。**仿真器不得从关卡导入这些常数**——
否则"关卡以为的机器人"和"仿真里的机器人"会一起错，端到端全绿而真机
必然出问题。历史上就出过这个错：仿真把 turn_left_small_step 写成
N(2.0, 1.5)°，与关卡共享同一个错数（真值是 8.625°），于是 20/20 全绿，
而真机上对正阶段必然来回过冲。

转向死区规则
------------
**死区（航向容差）必须 ≥ 该方向的转向步长，否则闭环会一直来回过冲。**
仓库里记过一次真实事故：死区 3.5° 小于步长 10°，真机"在死区打转"，
最后转出场地。左转一步就有 8.625°，所以航向容差取 ≥ 10°，
并要求"转一步、复测一次"，不做 n 步批量。
"""

# =====================================================================
# 已实测（2026-09-25）
# =====================================================================
# 命名与 core/robot_core.py:MOTION_BUDGET_CM / 动作组名一致。

#: 前进一大步（go_forward_one_step）
#:
#: ⚠ 2026-09-25 现场口径：**1.8cm/步**（换舵机 + 重装之后的现场读数）。
#:   同日早些时候实测的是 2.652cm/步（±3σ 0.055、组间极差 0.9cm/20步），
#:   两个数差 1.47 倍——大概率是重装后腿部舵机中位/步幅变了。
#:   **这一条直接决定所有"走几步"的推算**（末段推算、远距批量），
#:   所以下次上机第一件事就是复量：让机器人直走 20 步，量脚尖位移 ÷ 20。
#:   在复量之前，本文件按 1.8 走；旧值仅作为记录留在下面。
FWD_STEP_CM = 1.8
FWD_STEP_3SIGMA_CM = 0.055
FWD_STEP_GROUP_RANGE_CM = 0.900      # 20 步总量的组间极差（旧口径，未随 1.8 复量）
#: 旧口径（2026-09-25 重装前实测）：仅作记录，不要引用
FWD_STEP_CM_LEGACY = 2.652

#: 左横移一步（left_move）
LEFT_MOVE_CM = 2.497
LEFT_MOVE_3SIGMA_CM = 0.144
LEFT_MOVE_GROUP_RANGE_CM = 1.100     # 10 步总量

#: 左转一小步（turn_left_small_step）——**很散，且比右转大一倍**
TURN_LEFT_DEG = 8.625
TURN_LEFT_3SIGMA_DEG = 1.875
TURN_LEFT_GROUP_RANGE_DEG = 25.000   # 20 步总量

#: 右转一小步（turn_right_small_step）——很稳
TURN_RIGHT_DEG = 5.200
TURN_RIGHT_3SIGMA_DEG = 0.150
TURN_RIGHT_GROUP_RANGE_DEG = 2.000   # 20 步总量

#: 单次拍照耗时（秒），用于时间预算（不是动作，但同属现场实测常数）
CAPTURE_SECONDS = 0.9


# =====================================================================
# 尚未实测——不要当成已知值使用
# =====================================================================
# 下面三个动作没有实测数据。它们撑着"视觉丢失时不弃赛"的降级链，
# 用之前必须先量；在此之前只能作为最粗的估计。
FWD_SMALL_STEP_CM = None    # go_forward_one_small_step
BACK_STEP_CM = None         # back_one_step
RIGHT_MOVE_CM = None        # right_move


# =====================================================================
# 派生量
# =====================================================================

def turn_step_deg(direction: str) -> float:
    """该方向的单步转角（度）。direction: 'left' | 'right'"""
    if direction == "left":
        return TURN_LEFT_DEG
    if direction == "right":
        return TURN_RIGHT_DEG
    raise ValueError(f"未知转向方向: {direction!r}")

#: 最大单步转角——航向容差的下界
MAX_TURN_STEP_DEG = max(TURN_LEFT_DEG, TURN_RIGHT_DEG)

#: 建议的航向容差下界（≥ MAX_TURN_STEP_DEG，留一点测量噪声余量）
ALIGN_TOL_MIN_DEG = 10.0
