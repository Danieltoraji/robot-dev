PNP_REPROJ_ERR_MAX_MULTI_PX = 11.0


def reproj_gate_px(n_tags):
    """按帧内标签数选择重投影门控阈值（1 个 = 2px，多个 = 8px）"""
    return PNP_REPROJ_ERR_MAX_PX if n_tags <= 1 else PNP_REPROJ_ERR_MAX_MULTI_PX
