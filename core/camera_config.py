# 做场地自标定修复 tag_poses，而不是放宽此阈值。
# 场地范围门控：±5cm 余量。真值光心最远 ≈ 100+|e|≈103.5 仍在界内；
# 出口走廊的掠射视角会产生 106+ 的镜像分支假解（2026-08-30 角点桩仿真
# 实测 (109,30) 假解曾钻过 ±10 余量导致机器人走出场外），±5 可拦截。
