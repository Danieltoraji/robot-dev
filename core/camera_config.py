# =====================================================================
# PnP 位姿合理性门控
# =====================================================================
# solvePnP 对错误角点顺序也能给出「重投影误差≈0」的假位姿（正方形标签的
# 旋转/镜像歧义）。定位结果必须通过以下物理合理性检查，否则视为定位失败
