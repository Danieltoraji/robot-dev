#   为什么**不要**去"修正"它：
#   闭环在零点处两套公式同为零 ⇒ 收敛点不受影响；而这个 0.734 倍率事实上是
#   **整族 yaw 域阈值共同的隐含增益标定**（死区 VIS_ALIGN_TOL_DEG、
